"""既存の路面材質とトンネル筒から RainFX 設定を生成する。KN5 は変更しない。"""
import json
from pathlib import Path

import numpy as np
from shapely.geometry import Polygon

from . import config, tunnel


SOURCE_URL = 'https://github.com/ac-custom-shaders-patch/acc-extension-config/wiki/Tracks-%E2%80%93-RainFX'
MANIFEST_DIRS = ('track', 'dress_s3', 'dress_mountain', 'visual_updates', 'parking_props', 'horizon', 'environment')
PAINT = {'line_white', 'line_orange', 'paint_red', 'paint_green', 'text_tomare',
         'visual_line_white', 'visual_paint_red', 'visual_paint_green',
         'dress_line_white', 'dress_line_orange', 'dress_diamond', 'dress_text_40', 'dress_green', 'dress_red'}


def bore_occluders(vertices):
    """筒の隣接する断面ごとに水平上面を返す。出力は AC (東, 高さ, -北)。"""
    vertices = np.asarray(vertices, dtype=float)
    width = tunnel.N_ARC + 3
    if (vertices.ndim != 2 or vertices.shape[1] != 3 or len(vertices) < 2 * width
            or len(vertices) % width or not np.isfinite(vertices).all()):
        raise ValueError('トンネル断面の頂点配列が不正です')
    rows = vertices.reshape(-1, width, 3)
    result = []
    for a, b in zip(rows[:-1], rows[1:]):
        # 公式 RainFX の上面例と同じ頂点順（AC 座標で法線 Y < 0）。
        # 向きの効果は実機比較が必要だが、仕様例と逆の面を出力しない。
        top = np.array([a[0], a[-1], b[-1], b[0]])
        shape = Polygon(top[:, :2])
        if not shape.is_valid or shape.area < .01:
            raise ValueError('トンネル断面間の雨除け領域が不正です')
        top[:, 2] = max(a[:, 2].max(), b[:, 2].max()) + .02
        result.append(top[:, [0, 2, 1]] * [1, 1, -1])
    return result


def build(out_dir=None):
    root = Path(out_dir or config.DATA_PROCESSED / 'environment')
    manifests = {}
    for name in MANIFEST_DIRS:
        source = config.TRACK_BUILD_DIR if name == 'track' else config.DATA_PROCESSED / name
        path = source / 'manifest.json'
        if path.exists():
            manifests[name] = (source, json.loads(path.read_text()))
        elif name in ('track', 'visual_updates'):
            raise FileNotFoundError(f'雨設定の前に {path} を生成してください')
    materials = {name for _, m in manifests.values() for name in m['materials']}
    paint = materials & PAINT | {n for n in materials if n.startswith('mt_mark_')}
    soaking = materials & {'asphalt', 'concrete_circles', 'visual_concrete_circles', 'dress_patch'}
    rough = materials & {'ground', 'ground_far', 'visual_ground_far', 'horizon', 'tree', 'hedge',
                         'gravel', 'riverbed', 'wood', 'wood_bars', 'mt_leaves_edge', 'mt_leaves_lane',
                         'parking_trousers', 'parking_skin', 'parking_hair', 'parking_rubber'}
    rough |= {n for n in materials if n.startswith('parking_coat_')}
    smooth = materials & {'glass_grey', 'mirror', 'guardrail', 'railing', 'railing_bars',
                          'pole_grey', 'pole_orange', 'roof_metal', 'vending', 'vending_front', 'env_vending_front',
                          'parking_glass', 'parking_wheel', 'parking_headlamp', 'parking_taillamp',
                          'dress_mirror', 'dress_manhole', 'dress_grating', 'mt_guardrail', 'mt_bars'}
    smooth |= {n for n in materials if n.startswith('parking_body_')}
    # 水たまりは作らない（ユーザーの指示 2026-10-28：トンネルの中で出口を鏡のように映した。この道でそこまで要らない）。濡れと白線の濡れは残す
    values = {'PUDDLES_MATERIALS': [], 'PUDDLES_MESHES': [],
              'SOAKING_MATERIALS': sorted(soaking), 'SMOOTH_MATERIALS': sorted(smooth),
              'ROUGH_MATERIALS': sorted(rough), 'LINES_MATERIALS': sorted(paint)}
    text = '; Generated by yabitsu.environment_rain\n; ' + SOURCE_URL + '\n[RAIN_FX]\n'
    text += '\n'.join(f'{key}=' + ','.join(value) for key, value in values.items()) + '\n\n'
    report = {'source': SOURCE_URL, 'material_lists': values, 'occluders': {}, 'tunnel_count': 0,
              'note': '水たまりと走行線付近の差はCSP標準処理。実測した轍の凹凸・排水量ではない。'}
    source, original = manifests['track']
    for name, item in original['meshes'].items():
        if not (name.startswith('1WALL_tunnel_') and name.endswith('_bore')):
            continue
        vertices = np.load(source / item['file'])['verts']
        planes = bore_occluders(vertices)
        report['tunnel_count'] += 1
        for row, points in enumerate(planes):
            section = f'TRACK_OCCLUDER_BOX_{len(report["occluders"])}'
            text += f'[{section}]\nDESCRIPTION={name} segment {row}\n'
            text += '\n'.join(f'POINT_{i}=' + ','.join(f'{x:.4f}' for x in p)
                              for i, p in enumerate(points)) + '\n\n'
            report['occluders'][section] = {'mesh': name, 'row': row, 'points_ac': points.tolist()}
    path = root / 'extension/parts/rain.ini'
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding='utf-8')
    (root / 'rain_report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    return path, report
